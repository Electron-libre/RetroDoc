fn feature(slug: &str) -> Feature {
    Feature {
        back_office: false,
        technical: false,
        slug: slug.into(),
        domain_slug: "billing".into(),
        name: format!("Feature {slug}"),
        description: format!("What {slug} does"),
        source_paths: Vec::new(),
        entry_points: Vec::new(),
        confidence: None,
    }
}

fn use_case(narrative: &str) -> UseCase {
    UseCase {
        slug: "pay-by-card".into(),
        feature_slug: "pay-invoice".into(),
        name: "Pay by card".into(),
        description: String::new(),
        steps: Vec::new(),
        entry_points: Vec::new(),
        primary_actor: None,
        narrative: Some(narrative.into()),
        business_language: None,
        diagram_mermaid: None,
        confidence: None,
        narrative_check: None,
    }
}

/// A git repository of `user.name` `Ada` holding a run over `billing`: the features
/// `pay-invoice` (the use case `pay-by-card`) and `refund`.
fn generated_repo() -> tempfile::TempDir {
    let dir = tempfile::tempdir().unwrap();
    let root = dir.path();
    for args in [&["init", "-q"][..], &["config", "user.name", "Ada"]] {
        let status = std::process::Command::new("git")
            .args(args)
            .current_dir(root)
            .status()
            .unwrap();
        assert!(status.success());
    }
    retrodoc_pipeline::save_features(root, &[feature("pay-invoice"), feature("refund")]).unwrap();
    retrodoc_pipeline::save_use_cases(root, &[use_case("The clerk takes the card.")]).unwrap();
    DomainMap {
        domains: vec![DomainCluster {
            slug: "billing".into(),
            name: "Billing".into(),
            ..DomainCluster::default()
        }],
    }
    .save(root)
    .unwrap();
    dir
}

fn edit(root: &Path, section: &Section, fields: Fields) -> Edit {
    let docs = GeneratedDocs::load(root, &[]).unwrap();
    edits::record(root, &docs, section, fields).unwrap()
}

async fn get(root: &Path, path: &str) -> String {
    let project = Project {
        lang: Some("en"),
        ..Project::default()
    };
    let docs = GeneratedDocs::load(root, &[]);
    let response = retrodoc_web::router(project, docs, DocLinks::default(), Vec::new())
        .oneshot(Request::get(path).body(Body::empty()).unwrap())
        .await
        .unwrap();
    let status = response.status();
    let body = axum::body::to_bytes(response.into_body(), usize::MAX)
        .await
        .unwrap();
    let page = String::from_utf8(body.to_vec()).unwrap();
    assert_eq!(status, StatusCode::OK, "{page}");
    page
}

/// The edit block of a section page, `None` when it has none.
fn edit_block(page: &str) -> Option<&str> {
    let start = page.find("<section class=\"edit\"")?;
    let end = start + page[start..].find("</section>").unwrap();
    Some(&page[start..end])
}

// spec: WEB-91
#[tokio::test]
async fn the_page_of_an_edited_section_says_it_holds_a_human_edit() {
    let repo = generated_repo();
    let root = repo.path();
    let fields = Fields {
        name: Some("Settle an invoice".into()),
        description: Some("Pays what is due.".into()),
        ..Fields::default()
    };
    let saved = edit(
        root,
        &Section::new(SectionKind::Feature, "pay-invoice"),
        fields,
    );

    let page = get(root, "/domains/billing/pay-invoice").await;

    let block = edit_block(&page).unwrap_or_else(|| panic!("no edit block in {page}"));
    assert!(block.contains("Human edit"), "{block}");
    assert!(block.contains("name, description"), "{block}");
    assert!(
        block.contains(&format!("by Ada, {}", saved.edited_at)),
        "{block}"
    );
    assert!(!block.contains("Outdated edit"), "{block}");
    assert!(!block.contains("Generated by the last run"), "{block}");
    assert!(
        page.find("<section class=\"edit\"").unwrap()
            < page.find("<section class=\"review\"").unwrap(),
        "the edit before the review: {page}"
    );
    assert!(page.contains("<h1>Settle an invoice</h1>"), "{page}");
    let refund = get(root, "/domains/billing/refund").await;
    assert_eq!(edit_block(&refund), None, "{refund}");
}

// spec: WEB-92
#[tokio::test]
async fn an_outdated_edit_is_flagged_with_the_new_generated_text() {
    let repo = generated_repo();
    let root = repo.path();
    let fields = Fields {
        narrative: Some("The manager <b>approves</b> the card.".into()),
        ..Fields::default()
    };
    edit(
        root,
        &Section::use_case("pay-invoice", "pay-by-card"),
        fields,
    );
    retrodoc_pipeline::save_use_cases(root, &[use_case("The clerk scans the card.")]).unwrap();

    let page = get(root, "/domains/billing/pay-invoice/pay-by-card").await;

    let block = edit_block(&page).unwrap_or_else(|| panic!("no edit block in {page}"));
    assert!(
        block.contains("Outdated edit: section rewritten since the edit"),
        "{block}"
    );
    assert!(block.contains("Generated by the last run"), "{block}");
    assert!(block.contains("The clerk scans the card."), "{block}");
    assert!(
        page.contains(
            "<p class=\"narrative\">The manager &#60;b&#62;approves&#60;/b&#62; the card."
        ),
        "the edited narrative shown, escaped: {page}"
    );
    assert_eq!(
        page.matches("The clerk scans the card.").count(),
        1,
        "{page}"
    );
}

/// What the router answered a `POST`.
struct Answer {
    status: StatusCode,
    location: Option<String>,
    redirect: Option<String>,
    body: String,
}

async fn post(root: &Path, path: &str, form: &str, htmx: bool) -> Answer {
    let mut request = Request::post(path)
        .header("host", "127.0.0.1:8730")
        .header("origin", "http://127.0.0.1:8730")
        .header("content-type", "application/x-www-form-urlencoded");
    if htmx {
        request = request.header("hx-request", "true");
    }
    let docs = GeneratedDocs::load(root, &[]);
    let response = retrodoc_web::router(Project::default(), docs, DocLinks::default(), Vec::new())
        .oneshot(request.body(Body::from(form.to_string())).unwrap())
        .await
        .unwrap();
    let header = |name: &str| {
        response
            .headers()
            .get(name)
            .map(|v| v.to_str().unwrap().to_string())
    };
    let (status, location, redirect) =
        (response.status(), header("location"), header("hx-redirect"));
    let body = axum::body::to_bytes(response.into_body(), usize::MAX)
        .await
        .unwrap();
    Answer {
        status,
        location,
        redirect,
        body: String::from_utf8(body.to_vec()).unwrap(),
    }
}

/// The edits saved, as the store loads them.
fn saved(root: &Path) -> Vec<(Section, Fields)> {
    edits::load(root)
        .unwrap()
        .edits()
        .iter()
        .map(|e| (e.section.clone(), e.fields.clone()))
        .collect()
}

/// The edit form of a section page.
fn form_block(page: &str) -> &str {
    let start = page
        .find("<section class=\"edit-form\"")
        .unwrap_or_else(|| panic!("no edit form in {page}"));
    let end = start + page[start..].find("</section>").unwrap();
    &page[start..end]
}

const USE_CASE: &str = "/domains/billing/pay-invoice/pay-by-card";
const FEATURE: &str = "/domains/billing/pay-invoice";

// spec: WEB-93
#[tokio::test]
async fn the_edit_form_is_filled_with_the_text_the_page_shows() {
    let repo = generated_repo();
    let root = repo.path();
    edit(
        root,
        &Section::new(SectionKind::Feature, "pay-invoice"),
        Fields {
            name: Some("Settle <an> invoice".into()),
            ..Fields::default()
        },
    );

    let use_case = get(root, USE_CASE).await;
    let form = form_block(&use_case);
    assert!(
        form.contains(&format!("hx-post=\"/edit{USE_CASE}\"")),
        "{form}"
    );
    assert!(form.contains("value=\"Pay by card\""), "{form}");
    assert!(
        form.contains("name=\"narrative\" rows=\"8\">The clerk takes the card.</textarea>"),
        "{form}"
    );
    assert!(
        use_case.find("<section class=\"review\"").unwrap()
            < use_case.find("<section class=\"edit-form\"").unwrap(),
        "the form after the review: {use_case}"
    );

    let feature = get(root, FEATURE).await;
    let form = form_block(&feature);
    assert!(
        form.contains("value=\"Settle &#60;an&#62; invoice\""),
        "{form}"
    );
    assert!(form.contains(">What pay-invoice does</textarea>"), "{form}");
    assert!(!form.contains("name=\"narrative\""), "{form}");
    let domain = get(root, "/domains/billing").await;
    assert!(
        form_block(&domain).contains("hx-post=\"/edit/domains/billing\""),
        "{domain}"
    );
}

